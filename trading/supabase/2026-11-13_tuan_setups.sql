## Cách dùng bộ này
- Che nửa phải của chart, tự đoán hướng đi và điểm vào trước khi xem kết quả
- Để ý điểm vào nằm ở đâu so với cấu trúc giá: phá vỡ, test lại, vùng cung cầu
- So R:R của từng lệnh — lệnh đẹp thường có R:R từ 1:2 trở lên
- Thấy setup nào giống cách mình vào lệnh thì ghi lại vào Backtest

